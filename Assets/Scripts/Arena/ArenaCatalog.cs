        /// Как испытать событие: подсказка под описанием (пусто — просто смотреть или ехать в зону).
        public static string Hint(EventDefinition d)
        {
            if (d.Id == "hypergamy") return "Въедь в картинку или нажми «Коснуться картинки».";
            if (d.Gag) return "Появляется рядом с машиной — можно стоять или ехать.";
            if (d.Trigger) return "Ждёт, пока машина подъедет: езжай в зону или нажми «Сработать сейчас».";
            if (d.Kind == EventKind.Good) return "Польза: проедь через зону.";
            if (d.Sustain) return "Держится, пока машина не проедет зону (до 20 с).";
            return "";
        }

        public static string Description(string id) => Descriptions.TryGetValue(id, out var text) ? text : "";

        public static ArenaCategory Category(EventDefinition d) =>
            d.Spectacle ? ArenaCategory.Show : d.Gag ? ArenaCategory.Gag : d.Kind == EventKind.Good ? ArenaCategory.Good : ArenaCategory.Hazard;

        public static string CategoryName(ArenaCategory c) => c switch
        {
            ArenaCategory.Hazard => "ОПАСНОСТИ",
            ArenaCategory.Good => "ПОЛЬЗА",
            ArenaCategory.Gag => "ТРЮКИ",
            ArenaCategory.Show => "ШОУ",
            _ => "ВСЕ",
        };

        /// Короткая подпись типа события для строки списка.
        public static string Tag(EventDefinition d) => d.Spectacle ? "шоу" : d.Gag ? "трюк" : d.Kind == EventKind.Good ? "польза" : d.IsHeavy ? "тяжёлое" : "опасность";
